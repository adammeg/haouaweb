/** Helper — construit une ligne de table */
function r(
  wk: number,
  p3: number,
  p10: number,
  p50: number,
  p90: number,
  p97: number,
): [number, IgPercentiles] {
  return [wk, { p3, p10, p50, p90, p97 }];
}

